#Escape Sequence

#Escape Sequence means 
# \" Escape Double Quote - to include a " without ending it.
print("Hi \"Python\"")

# \\ Escape Backlash
print("Path: C:\\Users\\shiva")

# \n New Line
print("Message1\n") 
print("Message2")

# \t Escape Tab
print("Message1\tMessage2")

# """ - Allows to write text in multiple line strings
print("""Python is:
\n\tSimple
\n\tHign-Level language
\n\tInterpreted""")